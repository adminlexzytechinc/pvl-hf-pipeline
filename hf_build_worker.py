# ─────────────────────────────────────────────
#  ZIP Processing (flatten + filter + watermark)
# ─────────────────────────────────────────────

def should_exclude(entry_name: str) -> bool:
    """Check if a ZIP entry matches any exclude pattern."""
    basename = os.path.basename(entry_name)
    for pattern in EXCLUDE_PATTERNS:
        if fnmatch.fnmatch(basename, pattern) or fnmatch.fnmatch(entry_name, pattern):
            return True
    return False


def process_zip(source_path: str, output_path: str) -> dict:
    """
    Open the source ZIP and create a new output ZIP with:
    - Entries flattened (strip the top-level folder if there's only one)
    - Excluded patterns removed
    - Watermark files added at the root level

    Returns stats dict: {kept, excluded, watermarks, total_size}
    """
    report_progress("processing", 82, "Processing ZIP contents...", force=True)

    stats = {"kept": 0, "excluded": 0, "watermarks": 2, "total_size": 0}

    with zipfile.ZipFile(source_path, "r") as src_zip:
        entries = [e for e in src_zip.infolist() if not e.is_dir()]

        # Detect common top-level folder prefix (for flattening)
        prefix = detect_common_prefix(entries)

        CHUNK_SIZE = 64 * 1024 * 1024  # 64MB — memory stays flat regardless of entry size

        with zipfile.ZipFile(output_path, "w", zipfile.ZIP_STORED, allowZip64=True) as out_zip:
            for entry in entries:
                name = entry.filename

                # Strip the common prefix to flatten
                if prefix and name.startswith(prefix):
                    flat_name = name[len(prefix):]
                else:
                    flat_name = name

                if not flat_name or flat_name.endswith("/"):
                    continue

                # Check exclusion
                if should_exclude(flat_name):
                    stats["excluded"] += 1
                    print(f"  Excluded: {flat_name}")
                    continue

                # Stream entry to output in chunks — never buffers full file
                with src_zip.open(entry, "r") as src, \
                     out_zip.open(flat_name, "w", force_zip64=True) as dst:
                    while True:
                        chunk = src.read(CHUNK_SIZE)
                        if not chunk:
                            break
                        dst.write(chunk)

                stats["kept"] += 1
                stats["total_size"] += entry.file_size

            # Add watermark files at root
            out_zip.writestr(f"Downloaded from {BRAND_NAME}.txt", WATERMARK_BRAND)
            out_zip.writestr(f"README - Download Info.txt", WATERMARK_README)

    print(f"  Processed: {stats['kept']} kept, {stats['excluded']} excluded, "
          f"{stats['total_size'] // (1024*1024)} MB")
    return stats


def detect_common_prefix(entries: list) -> str:
    """
    If all entries share a single top-level folder, return it as a prefix
    so we can strip it (flatten the ZIP).
    e.g. all start with 'Tecno_Pova_8_5G_.../'' → return that prefix
    """
    if not entries:
        return ""

    # Get first path component of each entry
    tops = set()
    for e in entries:
        parts = e.filename.split("/")
        if len(parts) > 1:
            tops.add(parts[0])
        else:
            return ""  # File at root level — no common prefix

    if len(tops) == 1:
        prefix = tops.pop() + "/"
        print(f"  Flattening: stripping common prefix '{prefix}'")
        return prefix

    return ""


