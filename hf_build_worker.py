#  Google Drive Authentication (Service Account)
# ─────────────────────────────────────────────

_cached_token = None
_token_expiry = 0

def get_access_token() -> str:
    """Get a Google OAuth2 access token using the Service Account."""
    global _cached_token, _token_expiry

    if _cached_token and time.time() < _token_expiry:
        return _cached_token

    with open(SA_CREDENTIALS_PATH, "r") as f:
        creds = json.load(f)

    now = int(time.time())
    payload = {
        "iss":   creds["client_email"],
        "scope": "https://www.googleapis.com/auth/drive",
        "aud":   GOOGLE_TOKEN_URL,
        "iat":   now,
        "exp":   now + 3600,
    }

    token = jwt.encode(payload, creds["private_key"], algorithm="RS256")
    resp = requests.post(GOOGLE_TOKEN_URL, data={
        "grant_type": "urn:ietf:params:oauth:grant-type:jwt-bearer",
        "assertion":  token,
    }, timeout=30)
    resp.raise_for_status()
    data = resp.json()

    _cached_token = data["access_token"]
    _token_expiry = now + data.get("expires_in", 3600) - 60
    return _cached_token


