def upload_to_hf(file_path: str, hf_filename: str) -> str:
    """Upload a file to the Hugging Face dataset repo. Returns the download URL."""
    report_progress("uploading", 88, "Uploading to permanent cache...", force=True)

    api = HfApi(token=HF_TOKEN)

    # Upload the file
    api.upload_file(
        path_or_fileobj=file_path,
        path_in_repo=hf_filename,
        repo_id=HF_REPO_ID,
        repo_type="dataset",
        commit_message=f"Cache: {hf_filename}",
    )

    # Construct the direct download URL
    hf_url = f"https://huggingface.co/datasets/{HF_REPO_ID}/resolve/main/{hf_filename}"
    print(f"  Uploaded to HF: {hf_url}")
    return hf_url


