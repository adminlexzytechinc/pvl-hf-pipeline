def get_file_metadata(file_id: str) -> dict:
    """Fetch file metadata from Google Drive."""
    token = get_access_token()
    resp = requests.get(f"{DRIVE_API_BASE}/files/{file_id}", params={
        "fields": "id,name,mimeType,size",
        "supportsAllDrives": "true",
    }, headers={"Authorization": f"Bearer {token}"}, timeout=30)
    resp.raise_for_status()
    return resp.json()


# ─────────────────────────────────────────────
#  Download Cascade (mirrors PHP pvl_sa_download_to_temp)
# ─────────────────────────────────────────────

def download_file(file_id: str, dest_path: str) -> bool:
    """
    Download a file from Google Drive using the same cascade as the PHP engine:
      1. GAS Bridge copy
      2. GAS Bridge folder + signed URL
      3. Web download URL with SA Bearer token
      4. Standard Drive API download
    """
    # ─── Approach 1A: GAS Copy ───
    report_progress("downloading", 5, "Trying GAS copy...", force=True)
    if gas_try_copy(file_id, dest_path):
        return True

    # ─── Approach 1B: GAS Folder + Signed URL ───
    report_progress("downloading", 10, "Trying GAS folder download...")
    if gas_try_folder_download(file_id, dest_path):
        return True

    # ─── Approach 2: Web download URL ───
    report_progress("downloading", 15, "Trying web download URL...")
    if web_download(file_id, dest_path):
        return True

    # ─── Approach 3: Standard API ───
    report_progress("downloading", 20, "Trying API download...")
    if api_download(file_id, dest_path):
        return True

    return False


def gas_try_copy(file_id: str, dest_path: str) -> bool:
    """GAS Approach A: Server-side copy with fresh quota."""
    try:
        resp = requests.get(GAS_BRIDGE_URL, params={
            "action": "copy",
            "fileId": file_id,
            "secret": GAS_BRIDGE_SECRET,
        }, timeout=120)
        data = resp.json()

        if not data.get("success"):
            print(f"  GAS copy failed: {data.get('error', 'unknown')}")
            return False

        copy_id = data["copyId"]
        download_url = data["downloadUrl"]
        print(f"  GAS copy created: {copy_id}")

        # Download the copy
        success = stream_download(download_url, dest_path, auth=None)

        # Cleanup the copy
        try:
            requests.get(GAS_BRIDGE_URL, params={
                "action": "cleanup",
                "copyId": copy_id,
                "secret": GAS_BRIDGE_SECRET,
            }, timeout=30)
        except Exception:
            pass

        return success

    except Exception as e:
        print(f"  GAS copy error: {e}")
        return False


def gas_try_folder_download(file_id: str, dest_path: str) -> bool:
    """GAS Approach B: Folder + shortcut + signed URL."""
    try:
        resp = requests.get(GAS_BRIDGE_URL, params={
            "action":   "folder_download",
            "fileId":   file_id,
            "fileName": FILE_NAME,
            "secret":   GAS_BRIDGE_SECRET,
        }, timeout=120)
        data = resp.json()

        if not data.get("success"):
            print(f"  GAS folder failed: {data.get('error', 'unknown')}")
            return False

        folder_id  = data["folderId"]
        signed_url = data["signedUrl"]
        print(f"  GAS folder created: {folder_id}, got signed URL")

        # Download the folder ZIP
        zip_path = dest_path + ".folder.zip"
        if not stream_download(signed_url, zip_path, auth=None):
            cleanup_gas_folder(folder_id)
            return False

        # Extract target file from the folder ZIP
        success = extract_from_google_zip(zip_path, dest_path)
        os.unlink(zip_path)
        cleanup_gas_folder(folder_id)
        return success

    except Exception as e:
        print(f"  GAS folder error: {e}")
        return False


def web_download(file_id: str, dest_path: str) -> bool:
    """Approach 2: Web download URL with SA Bearer token."""
    try:
        token = get_access_token()
        url = f"https://drive.usercontent.google.com/download?id={file_id}&export=download&confirm=t"
        return stream_download(url, dest_path, auth=f"Bearer {token}")
    except Exception as e:
        print(f"  Web download error: {e}")
        return False


def api_download(file_id: str, dest_path: str) -> bool:
    """Approach 3: Standard Google Drive API download."""
    try:
        token = get_access_token()
        url = f"{DRIVE_API_BASE}/files/{file_id}"
        return stream_download(url, dest_path, auth=f"Bearer {token}",
                               params={"alt": "media", "supportsAllDrives": "true"})
    except Exception as e:
        print(f"  API download error: {e}")
        return False


def stream_download(url: str, dest_path: str, auth: str = None, params: dict = None) -> bool:
    """Stream a URL to a local file. Reports progress during download."""
    headers = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"}
    if auth:
        headers["Authorization"] = auth

    resp = requests.get(url, headers=headers, params=params, stream=True, timeout=30, allow_redirects=True)

    # Reject obvious HTML error pages (Google returns 200 + text/html for quota errors)
    content_type = resp.headers.get("Content-Type", "")
    if "text/html" in content_type:
        snippet = resp.content[:500].decode("utf-8", errors="replace")
        print(f"  Download returned HTML: {snippet[:200]}")
        return False

    total = int(resp.headers.get("Content-Length", 0))
    downloaded = 0

    with open(dest_path, "wb") as f:
        for chunk in resp.iter_content(chunk_size=65536):
            f.write(chunk)
            downloaded += len(chunk)
            if total > 0:
                pct = int((downloaded / total) * 60) + 20  # 20-80% range
                report_progress("downloading", pct,
                                f"Downloaded {downloaded // (1024*1024)} / {total // (1024*1024)} MB")

    size = os.path.getsize(dest_path)

    # Check if it's actually HTML despite the Content-Type header lying
    with open(dest_path, "rb") as f:
        head = f.read(256)
    if b"<!DOCTYPE" in head or b"<html" in head or b"Quota exceeded" in head:
        snippet = head[:200].decode("utf-8", errors="replace")
        print(f"  Download is HTML despite Content-Type ({content_type}): {snippet[:150]}")
        os.unlink(dest_path)
        return False

    # Reject suspiciously small files (any real firmware ZIP is at least several MB)
    if size < 1024:
        print(f"  Download too small: {size} bytes (expected a real file, not an error page)")
        os.unlink(dest_path)
        return False

    print(f"  Downloaded {size:,} bytes")
    return True


def extract_from_google_zip(zip_path: str, dest_path: str) -> bool:
    """Extract the largest non-directory file from a Google folder ZIP."""
    try:
        with zipfile.ZipFile(zip_path, "r") as zf:
            target = None
            target_size = 0
            for info in zf.infolist():
                if info.is_dir() or info.filename.startswith("."):
                    continue
                if info.file_size > target_size:
                    target = info
                    target_size = info.file_size

            if not target:
                print("  No files found in folder ZIP")
                return False

            with zf.open(target) as src, open(dest_path, "wb") as dst:
                shutil.copyfileobj(src, dst)

            print(f"  Extracted: {target.filename} ({target_size:,} bytes)")
            return True
    except Exception as e:
        print(f"  ZIP extraction error: {e}")
        return False


