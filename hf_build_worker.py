def download_file(file_id: str, dest_path: str) -> bool:
    """
    Download a file from storage source (Google Drive or MediaFire).
    """
    is_mediafire = (SOURCE_TYPE == "mediafire") or file_id.startswith("mf_") or ("mediafire.com" in SOURCE_URL)
    if is_mediafire:
        report_progress("downloading", 10, "Connecting to MediaFire source...", force=True)
        return mediafire_download(file_id, dest_path)

    # ─── Google Drive Cascade ───
    # ─── Approach 1A: GAS Copy ───
    report_progress("downloading", 5, "Trying GAS copy...", force=True)
    if gas_try_copy(file_id, dest_path):
        return True

    # ─── Approach 1B: GAS Folder + Signed URL ───
    report_progress("downloading", 10, "Trying GAS folder download...")
    if gas_try_folder_download(file_id, dest_path):
        return True

    # ─── Approach 2: Web download URL ───
    report_progress("downloading", 15, "Trying web download URL...")
    if web_download(file_id, dest_path):
        return True

    # ─── Approach 3: Standard API ───
    report_progress("downloading", 20, "Trying API download...")
    if api_download(file_id, dest_path):
        return True

    return False


def mediafire_download(file_id: str, dest_path: str) -> bool:
    """Download a file from MediaFire by resolving direct link from public page."""
    global FILE_NAME
    import re

    quickkey = file_id.replace("mf_", "").strip()
    page_url = SOURCE_URL if (SOURCE_URL and "mediafire.com" in SOURCE_URL) else f"https://www.mediafire.com/file/{quickkey}"

    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "en-US,en;q=0.5",
    }

    try:
        session = requests.Session()
        resp = session.get(page_url, headers=headers, timeout=30)
        if resp.status_code != 200:
            print(f"  MediaFire page returned HTTP {resp.status_code}")
            return False

        html = resp.text

        # Extract direct download link
        direct_url = None
        m = re.search(r'href=["\'](https?://download\d+\.mediafire\.com/[^"\']+)["\']', html, re.I)
        if m:
            direct_url = m.group(1)
        else:
            m = re.search(r'id=["\']downloadButton["\'][^>]*href=["\']([^"\']+)["\']', html, re.I)
            if m:
                direct_url = m.group(1)
            else:
                m = re.search(r'aria-label=["\']Download file["\'][^>]*href=["\']([^"\']+)["\']', html, re.I)
                if m:
                    direct_url = m.group(1)
                else:
                    m = re.search(r'https?://(?:www\.)?mediafire\.com/file_download/[^\s"\'<>]+', html, re.I)
                    if m:
                        direct_url = m.group(0)

        if not direct_url:
            print(f"  Could not extract direct download URL from MediaFire page: {page_url}")
            return False

        # Extract original filename from MediaFire HTML, direct URL, or SOURCE_URL
        scraped_fn = None
        fn_match = re.search(r'<div[^>]+class=["\'][^"\']*(?:file-name|filename)[^"\']*["\'][^>]*>([^<]+)</div>', html, re.I)
        if fn_match:
            scraped_fn = fn_match.group(1).strip()
        
        if not scraped_fn and direct_url:
            url_fn = direct_url.split("/")[-1].split("?")[0]
            if url_fn:
                scraped_fn = urllib.parse.unquote(url_fn)

        if not scraped_fn and SOURCE_URL:
            src_parts = [p for p in SOURCE_URL.split("?")[0].split("/") if p and p.lower() != "file"]
            if src_parts and "." in src_parts[-1]:
                scraped_fn = urllib.parse.unquote(src_parts[-1])

        if scraped_fn:
            scraped_clean = clean_watermarks(scraped_fn)
            if is_generic_filename(FILE_NAME) or ("." in scraped_clean and "." not in FILE_NAME):
                FILE_NAME = scraped_clean
                print(f"  Scraped MediaFire filename: {FILE_NAME}")

        print(f"  MediaFire direct download link found: {direct_url}")
        report_progress("downloading", 20, f"Downloading from MediaFire ({FILE_NAME})...")

        dl_resp = session.get(direct_url, headers=headers, stream=True, timeout=60)
        if dl_resp.status_code != 200:
            print(f"  MediaFire stream returned HTTP {dl_resp.status_code}")
            return False

        # Check Content-Disposition for filename
        cd = dl_resp.headers.get("Content-Disposition", "")
        if "filename=" in cd:
            cd_fn = re.search(r'filename=["\']?([^"\';]+)', cd)
            if cd_fn:
                cd_name = clean_watermarks(cd_fn.group(1).strip())
                if is_generic_filename(FILE_NAME) or ("." in cd_name and "." not in FILE_NAME):
                    FILE_NAME = cd_name
                    print(f"  Content-Disposition filename: {FILE_NAME}")

        total = int(dl_resp.headers.get("Content-Length", 0))
        downloaded = 0

        with open(dest_path, "wb") as f:
            for chunk in dl_resp.iter_content(chunk_size=65536):
                f.write(chunk)
                downloaded += len(chunk)
                if total > 0:
                    pct = int((downloaded / total) * 60) + 20
                    report_progress("downloading", pct,
                                    f"Downloaded {downloaded // (1024*1024)} / {total // (1024*1024)} MB")

        if os.path.getsize(dest_path) < 100:
            print("  MediaFire downloaded file is too small (<100 bytes)")
            return False

        print(f"  MediaFire download successful: {os.path.getsize(dest_path)} bytes")
        return True

    except Exception as e:
        print(f"  MediaFire download exception: {e}")
        traceback.print_exc()
        return False


def gas_try_copy(file_id: str, dest_path: str) -> bool:
    """GAS Approach A: Server-side copy with fresh quota."""
    try:
        resp = requests.get(GAS_BRIDGE_URL, params={
            "action": "copy",
            "fileId": file_id,
            "secret": GAS_BRIDGE_SECRET,
        }, timeout=120)
        data = resp.json()

        if not data.get("success"):
            print(f"  GAS copy failed: {data.get('error', 'unknown')}")
            return False

        copy_id = data["copyId"]
        download_url = data["downloadUrl"]
        print(f"  GAS copy created: {copy_id}")

        # Download the copy
        success = stream_download(download_url, dest_path, auth=None)

        # Cleanup the copy
        try:
            requests.get(GAS_BRIDGE_URL, params={
                "action": "cleanup",
                "copyId": copy_id,
                "secret": GAS_BRIDGE_SECRET,
            }, timeout=30)
        except Exception:
            pass

        return success

    except Exception as e:
        print(f"  GAS copy error: {e}")
        return False


def gas_try_folder_download(file_id: str, dest_path: str) -> bool:
    """GAS Approach B: Folder + shortcut + signed URL."""
    try:
        resp = requests.get(GAS_BRIDGE_URL, params={
            "action":   "folder_download",
            "fileId":   file_id,
            "fileName": FILE_NAME,
            "secret":   GAS_BRIDGE_SECRET,
        }, timeout=120)
        data = resp.json()

        if not data.get("success"):
            print(f"  GAS folder failed: {data.get('error', 'unknown')}")
            return False

        folder_id  = data["folderId"]
        signed_url = data["signedUrl"]
        print(f"  GAS folder created: {folder_id}, got signed URL")

        # Download the folder ZIP
        zip_path = dest_path + ".folder.zip"
        if not stream_download(signed_url, zip_path, auth=None):
            cleanup_gas_folder(folder_id)
            return False

        # Extract target file from the folder ZIP
        success = extract_from_google_zip(zip_path, dest_path)
        os.unlink(zip_path)
        cleanup_gas_folder(folder_id)
        return success

    except Exception as e:
        print(f"  GAS folder error: {e}")
        return False


