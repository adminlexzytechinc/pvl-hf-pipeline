import re as _re

def is_generic_filename(name: str) -> bool:
    """Check if a filename is a generic placeholder, file ID, or hash."""
    if not name:
        return True
    clean = str(name).strip()
    clean_lower = clean.lower()

    # 1. Exact generic words
    generic_words = (
        "download", "download.zip", "download.rar", "download.7z",
        "file", "file.zip", "file.rar", "file.7z",
        "raw_download", "raw_download.zip",
        "archive", "archive.zip",
        "document", "document.zip",
        "none", "null", "undefined",
        "get", "get.zip", "link", "link.zip",
        "mega", "mega.zip", "mega.nz", "mega.io", "maga", "maga.zip",
        "mediafire", "mediafire.com", "gdrive", "drive"
    )
    if clean_lower in generic_words:
        return True

    # 2. Check base name without extension
    base = os.path.splitext(clean)[0]
    base_lower = base.lower()
    if base_lower in generic_words:
        return True

    # Check if name is purely a domain name (e.g. mega.nz, mediafire.com)
    if _re.match(r'^[a-zA-Z0-9-]+\.(?:com|net|org|nz|io|co|in|xyz|biz|info)$', clean, _re.I):
        return True

    # 3. Exact match with FILE_ID
    if FILE_ID:
        if clean == FILE_ID or clean_lower == FILE_ID.lower():
            return True
        if base == FILE_ID or base_lower == FILE_ID.lower():
            return True
        # If FILE_ID is mf_xxx, check raw xxx
        if FILE_ID.startswith("mf_"):
            raw_mf_id = FILE_ID[3:].lower()
            if base_lower == raw_mf_id or clean_lower == raw_mf_id:
                return True
        # If FILE_ID is mega_xxx, check raw xxx
        if FILE_ID.startswith("mega_"):
            raw_mega_id = FILE_ID[5:].lower()
            if base_lower == raw_mega_id or clean_lower == raw_mega_id:
                return True

    # 4. Check if it's purely an ID prefix like pvl_... or mf_ or mega_ followed only by ID chars
    if _re.match(r'^(?:mf_|pvl_|mega_)[a-zA-Z0-9_-]{6,60}$', base, _re.I):
        return True

    # 5. Raw Google Drive ID / hash pattern (25-45 random alphanumeric chars, but NOT containing firmware separators/words)
    if "." not in clean:
        # If it has underscores, spaces, or hyphens separating words, it is a real firmware name
        if "_" in clean or " " in clean:
            return False
        # If it contains common firmware indicators, it's not a hash
        fw_indicators = ('mt6', 'mt8', 'qualcomm', 'snapdragon', 'exynos', 'unisoc', 'spd', 'firmware', 'flash', 'stock', 'rom', 'scatter', 'ota', 'build', 'global')
        if any(ind in clean_lower for ind in fw_indicators):
            return False
        # Pure random alphanumeric 25-50 chars with no spaces or underscores
        if _re.match(r'^[a-zA-Z0-9]{25,50}$', clean):
            return True

    return False

# Shared with pvl_strip_site_watermarks() in pvl-engine/pvl-match.php and, through
# it, firmware_clean_filename() in core.firmware.php. All three used to keep their
# own hardcoded roster of competitor names, so a mirror nobody had added yet leaked
# its domain into stored filenames. Keep the three in step.
_WM_TLDS = 'com|net|org|info|co|in|io|xyz|biz|me|us|ru|ir|vn|id'
_WM_EXTS = 'zip|rar|7z|pac|tar|gz|tgz|bz2|iso|bin|img|md5|ozip|kdz|dz|sin|ftf|nb0|app'
# No hyphens in the label, 3 characters minimum, and a negative lookahead rather
# than  -- underscore is a word character, so  does not fire between "com"
# and "_". See the comment in pvl-match.php for what each of those prevents.
_WM_DOMAIN = r'[a-z0-9]{3,}\.(?:' + _WM_TLDS + r')(?![a-z0-9])'


def match_decode(text: str) -> str:
    """Undo percent-encoding. Mirrors pvl_match_decode() in pvl-match.php.

    Mirrors hand back href-encoded filenames and nothing upstream decodes
    them, so "V551%20%282%29.zip" kept its escapes through every cleaning
    rule -- the "(" and ")" patterns never matched -- and the identity keys
    picked up "282" and "29" as digit-bearing tokens. The same build then
    keyed differently depending on which mirror it arrived from.

    unquote, never unquote_plus: "+" is a real character in device names
    ("Pouvoir 4 Pro+") and unquote_plus would turn it into a space.
    """
    if not text or "%" not in text:
        return text
    # Decode to a fixed point. MediaFire hands back DOUBLE-encoded segments --
    # "%2528" is an encoded "%28" is an encoded "(" -- so one pass leaves
    # escapes the watermark rules cannot match. A fixed point is idempotent
    # for free: fully decoded text decodes to itself. Bounded so nested input
    # cannot spin.
    for _ in range(4):
        decoded = urllib.parse.unquote(text)
        if decoded == text:
            break
        text = decoded
    return text


def strip_site_watermarks(filename: str) -> str:
    """Remove any domain-shaped token from a filename, keeping the extension."""
    filename = match_decode(filename)
    if not filename:
        return ""

    ext = ""
    m = _re.match(r'^(.*?)(\.(?:' + _WM_EXTS + r'))$', filename, _re.I)
    if m:
        filename, ext = m.group(1), m.group(2)

    filename = _re.sub(r'[\s_-]*\[[^\]]*\][\s_-]*', '_', filename)
    filename = _re.sub(r'^[\s_(\[-]*(?:up[_\s-]+)?(?:www\.)?' + _WM_DOMAIN + r'[)\]_\s-]*',
                       '', filename, flags=_re.I)
    filename = _re.sub(r'[_\-\s]*(?:by[_\s-]*)?[(\[]?\s*(?:www\.)?' + _WM_DOMAIN + r'.*$',
                       '', filename, flags=_re.I)
    filename = _re.sub(r'_{2,}', '_', filename)
    filename = _re.sub(r'-{2,}', '-', filename)
    filename = filename.strip(' 	_-([')
    # FIXED 2026-09-24 (same as pvl_strip_site_watermarks in pvl-match.php):
    # the long/medium dashes of this site's own older branding
    # ("..._190417 — lexzytechinc.com.zip") were left behind as "..._190417 —".
    filename = filename.strip(' \t_-([–—')
    # ADDED 2026-09-24 (same rule in pvl-match.php): MobiFirmware's "+" between
    # a dated build number and its watermark goes with the watermark.
    filename = _re.sub(r'(\d{6}V\d+|V\d+_\d{6})\+(?=$|\()', r'\1', filename, flags=_re.I)

    return filename + ext


def clean_watermarks(filename: str) -> str:
    """Strip third-party site watermarks from firmware filenames and archive entries.
    Mirrors firmware_clean_filename() from core.firmware.php.
    """
    if not filename:
        return ""
    c = match_decode(filename)

    # 1. Bracket watermarks at start: [up_addROM.com]_, [Hovatek], [NaijaROM], [FirmwareFile], etc.
    c = _re.sub(r'^\[[^\]]+\]\s*_?', '', c)

    # 2. _[HardReset.info] or similar anywhere
    c = _re.sub(r'_?\[[^\]]+\]', '', c)

    # 3. Leading site domain prefix: "up_addROM.com_", "www.site.com-", "site.com_", etc.
    c = _re.sub(r'^(?:up_)?(?:www\.)?[a-zA-Z0-9]+\.(?:com|net|org|co|in|info|io|xyz|biz)[_\s-]+', '', c, flags=_re.I)

    # 4. _by_(FirmwareOS.com) -- specific pattern BEFORE general parens removal
    c = _re.sub(r'_?by_?\(?[a-zA-Z0-9_-]+(?:\.[a-zA-Z]{2,6})?\)?', '', c, flags=_re.I)

    # 5. Site names in parentheses: (MobiFirmware.com), (by_NaijaROM.Com), (firmwarefile.com), etc.
    c = _re.sub(r'\([^)]*\.(?:com|net|org|io|co|in|info|xyz|biz)[^)]*\)', '', c, flags=_re.I)

    # 6. Parenthesized by-watermarks even without .com: _(by_SiteName), _(by_NaijaROM), _(by_)
    c = _re.sub(r'_?\(by[_\s][^)]*\)', '', c, flags=_re.I)

    # 7. Standalone site name references in filenames
    c = _re.sub(r'[\s_-]*(?:addROM|TecnoFirmware|NaijaROM|FirmwareFile|MobiFirmware|XDAFirmware|Firmware4mobile|Firmware4mobiles|Repairmymobile|RepairMyMobile|FirmwareOS|HardReset|MobileGuru4|Rom2box|Samfw|EasyFirmware)\.(?:com|net|org|co|in|info|io|xyz)[\s_-]*', '_', c, flags=_re.I)

    # 8. _by_AnySiteName before extension
    c = _re.sub(r'_by_[a-zA-Z0-9_\.]+(?=\.(?:zip|rar|7z|pac|tar|gz|iso|bin|img)$)', '', c, flags=_re.I)

    # 9. _Repairmymobile / _ RepairMyMobile.in suffix before extension
    c = _re.sub(r'[\s_-]+Repairmymobile(?:\.(?:co|in))?(?=\.(?:zip|rar|7z|pac|tar|gz|iso|bin|img)$)', '', c, flags=_re.I)

    # 10. _RMM suffix (RepairMyMobile abbreviation)
    c = _re.sub(r'_?RMM(?=\.(?:zip|rar|7z|pac|tar|gz|iso|bin|img)$)', '', c, flags=_re.I)

    # 11. _Firmware4mobile suffix before extension
    c = _re.sub(r'_?Firmware4mobiles?(?=\.(?:zip|rar|7z|pac|tar|gz|iso|bin|img)$)', '', c, flags=_re.I)

    # 12. _MobileGuru4.com / _MobileGuru4 suffix before extension
    c = _re.sub(r'_?MobileGuru4(?:\.com)?(?=\.(?:zip|rar|7z|pac|tar|gz|iso|bin|img)$)', '', c, flags=_re.I)

    # 13. Catch-all: trailing _by or _by_ before extension
    c = _re.sub(r'[_\s-]+by[_\s]*(?=\.(?:zip|rar|7z|pac|tar|gz|iso|bin|img)$)', '', c, flags=_re.I)

    # 14. Cleanup: double underscores/dashes
    c = _re.sub(r'_{2,}', '_', c)
    c = _re.sub(r'-{2,}', '-', c)

    # 15. Trailing underscore/dash before extension
    c = _re.sub(r'[_-]+\.(?=zip|rar|7z|pac|tar|gz|iso|bin|img)', '.', c, flags=_re.I)

    # 16. Leading underscore/dash
    c = _re.sub(r'^[_-]+', '', c)

    # 17. Generic pass: any remaining domain, named in the roster above or not.
    c = strip_site_watermarks(c)

    return c.strip()


