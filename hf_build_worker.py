def should_exclude(entry_name: str) -> bool:
    """Check if a ZIP entry matches any exclude pattern."""
    basename = os.path.basename(entry_name)
    for pattern in EXCLUDE_PATTERNS:
        if fnmatch.fnmatch(basename, pattern) or fnmatch.fnmatch(entry_name, pattern):
            return True
    return False


def is_extractable_archive(filepath: str, original_name: str) -> bool:
    """Check if the downloaded file is a compressed archive that should be unpacked."""
    ext = os.path.splitext(original_name)[1].lower()
    if ext in STANDALONE_EXTENSIONS:
        return False
    if ext in EXTRACTABLE_EXTENSIONS:
        return True
    if zipfile.is_zipfile(filepath):
        return True
    try:
        res = subprocess.run(["7z", "l", filepath], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if res.returncode == 0:
            return True
    except Exception:
        pass
    return False


def flatten_staging_dir(staging_dir: str):
    """If all extracted items sit inside a single top-level folder, hoist them up to root."""
    while True:
        items = os.listdir(staging_dir)
        if len(items) == 1 and os.path.isdir(os.path.join(staging_dir, items[0])):
            sub = os.path.join(staging_dir, items[0])
            print(f"  Flattening single top-level directory: {items[0]}")
            for child in os.listdir(sub):
                shutil.move(os.path.join(sub, child), os.path.join(staging_dir, child))
            os.rmdir(sub)
        else:
            break


def filter_and_clean_staging(staging_dir: str) -> dict:
    """
    Recursively walk staging_dir bottom-up:
    - Delete excluded files and directories (SP Flash Tool, Drivers, *.url, etc.)
    - Count kept files and total size
    NOTE: Internal filenames are NEVER renamed. Only the outer ZIP name gets
    cleaned/branded. This prevents corruption of firmware component names
    like APDB_MT6761_S01__W2104 and Checksum.ini.
    """
    stats = {"kept": 0, "excluded": 0, "total_size": 0}

    for root, dirs, files in os.walk(staging_dir, topdown=False):
        # 1. Process files -- delete excluded, count the rest
        for fname in files:
            fpath = os.path.join(root, fname)
            rel_path = os.path.relpath(fpath, staging_dir).replace("\\", "/")

            if should_exclude(rel_path) or should_exclude(fname):
                try:
                    os.remove(fpath)
                    stats["excluded"] += 1
                    print(f"  Excluded file: {rel_path}")
                except OSError:
                    pass
                continue

            stats["kept"] += 1
            try:
                stats["total_size"] += os.path.getsize(fpath)
            except OSError:
                pass

        # 2. Process directories -- delete excluded
        for dname in dirs:
            dpath = os.path.join(root, dname)
            rel_dpath = os.path.relpath(dpath, staging_dir).replace("\\", "/")

            if should_exclude(rel_dpath) or should_exclude(dname):
                try:
                    shutil.rmtree(dpath, ignore_errors=True)
                    stats["excluded"] += 1
                    print(f"  Excluded directory: {rel_dpath}")
                except OSError:
                    pass
                continue

    return stats


def restructure_staging_for_packaging(staging_dir: str, add_branding: bool = True):
    """Move all firmware files into firmware/ subfolder.
    If a firmware/ folder already exists (case-insensitive), reuse it instead
    of creating a nested firmware/firmware/ structure.
    Optionally add branding files at root level (outside firmware/).
    """
    # Check if there's already a firmware/ directory (case-insensitive)
    existing_firmware = None
    for item in os.listdir(staging_dir):
        if item.lower() == "firmware" and os.path.isdir(os.path.join(staging_dir, item)):
            existing_firmware = item
            break

    if existing_firmware:
        # Already has a firmware folder -- normalize case if needed
        if existing_firmware != "firmware":
            old_path = os.path.join(staging_dir, existing_firmware)
            new_path = os.path.join(staging_dir, "firmware")
            os.rename(old_path, new_path)
            print(f"  Renamed existing {existing_firmware}/ -> firmware/")

        # Move any remaining root-level files INTO firmware/
        firmware_dir = os.path.join(staging_dir, "firmware")
        for item in os.listdir(staging_dir):
            if item.lower() == "firmware":
                continue
            src = os.path.join(staging_dir, item)
            dst = os.path.join(firmware_dir, item)
            shutil.move(src, dst)
        print("  Reused existing firmware/ folder")
    else:
        # No firmware folder -- create one and move everything in
        firmware_dir = os.path.join(staging_dir, "firmware")
        os.makedirs(firmware_dir, exist_ok=True)
        for item in os.listdir(staging_dir):
            if item == "firmware":
                continue
            src = os.path.join(staging_dir, item)
            dst = os.path.join(firmware_dir, item)
            shutil.move(src, dst)
        print("  Created firmware/ subfolder")

    if add_branding:
        _write_branding_files(staging_dir)


def _write_branding_files(target_dir: str):
    """Write all branding files (text + InternetShortcut) into target_dir."""
    readme_path = os.path.join(target_dir, "README - Download Info.txt")
    with open(readme_path, "w", encoding="utf-8") as f:
        f.write(WATERMARK_README)

    brand_path = os.path.join(target_dir, f"Downloaded from {BRAND_NAME}.txt")
    with open(brand_path, "w", encoding="utf-8") as f:
        f.write(WATERMARK_BRAND)

    url_path = os.path.join(target_dir, f"{BRAND_NAME}.url")
    with open(url_path, "w", encoding="utf-8") as f:
        f.write(WATERMARK_URL)


def repack_staging_to_zip(staging_dir: str, output_zip_path: str, root_folder: str = ""):
    """Stream all files from staging_dir into a ZIP64 archive without high memory usage.
    If root_folder is set, all ZIP entry paths are prefixed with it to create
    a single top-level folder inside the ZIP.
    """
    CHUNK_SIZE = 64 * 1024 * 1024  # 64MB streaming buffer
    with zipfile.ZipFile(output_zip_path, "w", zipfile.ZIP_STORED, allowZip64=True) as out_zip:
        for root, _, files in os.walk(staging_dir):
            for fname in files:
                fpath = os.path.join(root, fname)
                rel_path = os.path.relpath(fpath, staging_dir).replace("\\", "/")
                if root_folder:
                    rel_path = f"{root_folder}/{rel_path}"
                with open(fpath, "rb") as src, \
                     out_zip.open(rel_path, "w", force_zip64=True) as dst:
                    while True:
                        chunk = src.read(CHUNK_SIZE)
                        if not chunk:
                            break
                        dst.write(chunk)


NESTED_ARCHIVE_EXTS = (".zip", ".7z", ".rar")
LOCKED_SHARE_LIMIT = 0.5   # refuse when over half the firmware, by size, is locked


def _archive_lock_state(path: str):
    """(locked_bytes, total_bytes) for one archive's members, read by `7z l -slt`.

    An empty password (-p) makes 7z answer instead of prompting. An archive
    whose file LIST is itself encrypted cannot be listed at all; that is
    reported as fully locked.
    """
    try:
        res = subprocess.run(["7z", "l", "-slt", "-p", path], stdin=subprocess.DEVNULL,
                             stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=300)
    except Exception:
        return 0, 0
    out = res.stdout.decode("utf-8", errors="replace")
    err = res.stderr.decode("utf-8", errors="replace")
    if "Wrong password" in err or "Can not open encrypted archive" in err:
        size = os.path.getsize(path)
        return size, size
    locked = total = 0
    size, enc, folder = 0, False, False
    for line in out.splitlines() + [""]:
        if line.startswith("Size = "):
            try:
                size = int(line[7:].strip() or 0)
            except ValueError:
                size = 0
        elif line.startswith("Encrypted = "):
            enc = line.strip().endswith("+")
        elif line.startswith("Folder = "):
            folder = line.strip().endswith("+")
        elif line.strip() == "":
            if size and not folder:
                total += size
                if enc:
                    locked += size
            size, enc, folder = 0, False, False
    return locked, total


def find_password_locked(staging_dir: str) -> str:
    """A reason to refuse the build, or '' when the firmware is usable.

    Added 2026-09-24 after a real case. "Tecno Pouvoir 1 LA6 MT6580 7.0 Dead
    Recovery ... Factroy Signed Firmware" passed every check and was published:
    its outer archive is intact, but the firmware inside it is a second archive
    with 17 of 18 files password-protected, shipped beside a "Contact Me For
    Password" folder holding AnyDesk, UltraViewer and a stranger's email -- a
    pay-for-the-password package. Every download of it was unusable.

    Only archives INSIDE the extracted package are examined (an encrypted outer
    archive already fails extraction). Measured by bytes, so a small locked
    extra such as a tools archive does not reject real firmware beside it.
    """
    total_bytes = 0
    locked_bytes = 0
    worst = ""
    for root, _dirs, files in os.walk(staging_dir):
        for name in files:
            path = os.path.join(root, name)
            try:
                size = os.path.getsize(path)
            except OSError:
                continue
            total_bytes += size
            if not name.lower().endswith(NESTED_ARCHIVE_EXTS):
                continue
            inner_locked, inner_total = _archive_lock_state(path)
            if inner_total and inner_locked / inner_total > LOCKED_SHARE_LIMIT:
                locked_bytes += size
                if not worst:
                    worst = name
    if total_bytes and locked_bytes / total_bytes > LOCKED_SHARE_LIMIT:
        return ("Firmware is password-protected (%s): %d%% of the package is locked "
                "and cannot be flashed, so it was not uploaded."
                % (worst, round(100 * locked_bytes / total_bytes)))
    return ""


def process_archive(source_path: str, output_path: str, original_name: str,
                    root_folder: str = "", clean_output_path: str = "",
                    add_branding: bool = True) -> dict:
    """
    Extract archive (.rar, .7z, .zip, .tar), filter exclusions,
    restructure into firmware/ subfolder, optionally add brand text files,
    and repack into a clean ZIP archive.

    Internal filenames are NEVER modified -- only excluded files are removed.

    Args:
        source_path: Path to the downloaded archive
        output_path: Destination for the ZIP
        original_name: Original filename (for extraction fallback)
        root_folder: Top-level folder name inside the ZIP
        clean_output_path: If set, also build a clean (unbranded) ZIP here
        add_branding: Write the branding files into the archive. False under
            SERVE_TIME_BRANDING, where the Worker appends them per request and
            the stored payload must stay brand-neutral.
    """
    # ADDED 2026-09-24: a ZIP is repacked by copying its compressed bytes
    # (zip_passthrough.py) -- no 25% growth, no extraction, seconds not
    # minutes. Same files in the same places; anything it has not been proven
    # on falls through to the extract-and-store path below, unchanged.
    if not clean_output_path and zipfile.is_zipfile(source_path):
        report_progress("processing", 81, "Checking archive contents...", force=True)
        locked = find_password_locked_in_zip(source_path)
        if locked:
            raise RuntimeError(locked)
        extra = None
        if add_branding:
            extra = {"README - Download Info.txt": WATERMARK_README.encode("utf-8"),
                     f"Downloaded from {BRAND_NAME}.txt": WATERMARK_BRAND.encode("utf-8"),
                     f"{BRAND_NAME}.url": WATERMARK_URL.encode("utf-8")}
        try:
            report_progress("processing", 83, "Repacking without recompressing...", force=True)
            stats = zip_passthrough.passthrough_repack(source_path, output_path, EXCLUDE_PATTERNS,
                                                       root_folder=root_folder, extra_files=extra)
            print(f"  Direct copy: {stats['kept']} files kept, {stats['excluded']} excluded, "
                  f"{stats['total_size'] // (1024*1024)} MB")
            return stats
        except zip_passthrough.Decline as e:
            print(f"  Direct copy not used ({e}); extracting instead")

    report_progress("processing", 81, "Extracting archive contents...", force=True)
    staging_dir = tempfile.mkdtemp(prefix="pvl_stage_")

    try:
        # Extract using 7z (handles RAR, 7Z, ZIP, TAR, etc. uniformly)
        extracted = False
        try:
            res = subprocess.run(["7z", "x", "-y", f"-o{staging_dir}", source_path],
                                 stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            if res.returncode == 0:
                extracted = True
            else:
                err_output = res.stderr.decode("utf-8", errors="replace").strip() or res.stdout.decode("utf-8", errors="replace").strip()
                err_lines = [line.strip() for line in err_output.splitlines() if line.strip()]
                short_err = " | ".join(err_lines[-3:]) if err_lines else f"exit code {res.returncode}"
                print(f"  7z extraction returned code {res.returncode}: {short_err}")
        except FileNotFoundError:
            pass

        # Fallback to Python zipfile if 7z isn't available and it's a zip
        if not extracted and zipfile.is_zipfile(source_path):
            print("  Attempting extraction via Python zipfile fallback...")
            with zipfile.ZipFile(source_path, "r") as zf:
                zf.extractall(staging_dir)
            extracted = True

        if not extracted:
            raise RuntimeError(f"Could not extract archive {original_name}")

        # FIXED 2026-09-24: refuse firmware that is password-locked inside.
        locked = find_password_locked(staging_dir)
        if locked:
            raise RuntimeError(locked)

        # Flatten staging directory if there's a single top-level folder
        flatten_staging_dir(staging_dir)

        # Remove excluded files only -- NO renaming of internal filenames
        report_progress("processing", 83, "Removing exclusions...", force=True)
        stats = filter_and_clean_staging(staging_dir)

        # Move all files into firmware/ subfolder (no branding yet)
        restructure_staging_for_packaging(staging_dir, add_branding=False)

        # If dual-build is on, repack the clean version FIRST (firmware/ only)
        if clean_output_path:
            report_progress("processing", 84, "Packaging clean ZIP...", force=True)
            clean_folder = root_folder.replace(f" - {BRAND_NAME}", "")
            repack_staging_to_zip(staging_dir, clean_output_path, root_folder=clean_folder)
            print(f"  Clean ZIP built: {clean_folder}.zip")

        if add_branding:
            # Add branding files at root (outside firmware/)
            _write_branding_files(staging_dir)
            report_progress("processing", 84, "Packaging branded ZIP...", force=True)
        else:
            # Serve-time branding: nothing brand-specific goes in the archive.
            report_progress("processing", 84, "Packaging brand-neutral ZIP...", force=True)

        repack_staging_to_zip(staging_dir, output_path, root_folder=root_folder)

        print(f"  Processed archive: {stats['kept']} files kept, {stats['excluded']} excluded, "
              f"{stats['total_size'] // (1024*1024)} MB")
        return stats

    finally:
        shutil.rmtree(staging_dir, ignore_errors=True)


def find_password_locked_in_zip(zip_path: str) -> str:
    """find_password_locked(), for the passthrough: the same verdict, read
    from the central directory, extracting only the archives inside."""
    total_bytes = locked_bytes = 0
    worst = ""
    with zipfile.ZipFile(zip_path) as zf:
        infos = [i for i in zf.infolist() if not i.is_dir()]
        total_bytes = sum(i.file_size for i in infos)
        for info in infos:
            leaf = info.filename.replace("\\", "/").rsplit("/", 1)[-1]
            if not leaf.lower().endswith(NESTED_ARCHIVE_EXTS):
                continue
            tmp = tempfile.mkdtemp(prefix="pvl_nested_")
            try:
                path = os.path.join(tmp, "inner" + os.path.splitext(leaf)[1].lower())
                with zf.open(info) as src, open(path, "wb") as dst:
                    shutil.copyfileobj(src, dst, 16 * 1024 * 1024)
                inner_locked, inner_total = _archive_lock_state(path)
            finally:
                shutil.rmtree(tmp, ignore_errors=True)
            if inner_total and inner_locked / inner_total > LOCKED_SHARE_LIMIT:
                locked_bytes += info.file_size
                if not worst:
                    worst = leaf
    if total_bytes and locked_bytes / total_bytes > LOCKED_SHARE_LIMIT:
        return ("Firmware is password-protected (%s): %d%% of the package is locked "
                "and cannot be flashed, so it was not uploaded."
                % (worst, round(100 * locked_bytes / total_bytes)))
    return ""


def archive_entries(path: str) -> list:
    """The archive's file list as [{'name', 'size'}], or [] if it cannot be read.
    A zip is read from its central directory; anything else through 7z."""
    try:
        if zipfile.is_zipfile(path):
            with zipfile.ZipFile(path) as zf:
                return [{"name": i.filename, "size": i.file_size}
                        for i in zf.infolist() if not i.is_dir()]
        res = subprocess.run(["7z", "l", "-slt", "-p", path], stdin=subprocess.DEVNULL,
                             stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=300)
        out = res.stdout.decode("utf-8", errors="replace")
        cur, entries, started = {}, [], False
        for line in out.splitlines() + [""]:
            if line.startswith("----------"):
                started = True
                continue
            if not started:
                continue
            if line.startswith("Path = "):
                cur = {"name": line[7:]}
            elif line.startswith("Size = ") and cur:
                cur["size"] = int(line[7:].strip() or 0)
            elif line.startswith("Folder = +"):
                cur = {}
            elif not line.strip() and cur.get("name"):
                entries.append(cur)
                cur = {}
        return entries
    except Exception as e:
        print(f"  Could not list the archive ({e})")
        return []


def package_standalone_file(raw_path: str, output_path: str, original_name: str,
                           root_folder: str = "", add_branding: bool = True):
    """
    For disk images (.iso) and standalone binaries (.pac, .img, .bin):
    Place the intact file into firmware/ subfolder under its EXACT original name,
    along with the download branding text files at the root level.

    Structure: {root_folder}/firmware/{original_name}
               {root_folder}/README - Download Info.txt
               {root_folder}/Downloaded from lexzytechinc.com.txt
    """
    report_progress("processing", 82, "Packaging standalone file...", force=True)

    CHUNK_SIZE = 64 * 1024 * 1024
    firmware_prefix = f"{root_folder}/firmware" if root_folder else "firmware"
    root_prefix = root_folder if root_folder else ""

    with zipfile.ZipFile(output_path, "w", zipfile.ZIP_STORED, allowZip64=True) as out_zip:
        # Write the firmware file into firmware/ subfolder with its original name
        inner_path = f"{firmware_prefix}/{original_name}"
        with open(raw_path, "rb") as src, \
             out_zip.open(inner_path, "w", force_zip64=True) as dst:
            while True:
                chunk = src.read(CHUNK_SIZE)
                if not chunk:
                    break
                dst.write(chunk)

        # Write branding files at root level (outside firmware/).
        # Skipped under SERVE_TIME_BRANDING -- the Worker appends them instead.
        if add_branding:
            brand_prefix = f"{root_prefix}/" if root_prefix else ""
            out_zip.writestr(f"{brand_prefix}Downloaded from {BRAND_NAME}.txt", WATERMARK_BRAND)
            out_zip.writestr(f"{brand_prefix}README - Download Info.txt", WATERMARK_README)
            out_zip.writestr(f"{brand_prefix}{BRAND_NAME}.url", WATERMARK_URL)

    print(f"  Packaged standalone file: {original_name} (unchanged name)")


